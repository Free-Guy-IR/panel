from collections import Counter
from pathlib import Path

SCRIPT_EXTENSIONS = (".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs")
JSONC_FILES = re.compile(r"^(tsconfig|jsconfig)(\.[\w-]+)*\.json$|\.code-workspace$")
HASH_EXTENSIONS = (
    ".yml",
    ".yaml",
    ".sh",
    ".toml",
    ".mk",
    ".mako",
    ".env.example",
    ".env.sample",
    ".env.template",
    ".env.dist",
)
MAKEFILES = {"Makefile", "makefile", "GNUmakefile"}
IGNORE_FILES = (".gitignore", ".dockerignore")
SKIPPED_PREFIXES = (".specify/",)
GENERATED_FILES = {"dashboard/src/service/api/index.ts"}
MIGRATIONS = "app/db/migrations/versions/"
ALEMBIC_LINES = {
    "# revision identifiers, used by Alembic.",
    "# ### commands auto generated by Alembic - please adjust! ###",
    "# ### end Alembic commands ###",
}
FRAGMENTS = {"#", "//", "/*", "/**", "/*!", "*", "*/", "<!--", "-->", "{#", "#}", ";"}
PRAGMAS = [
    re.compile(pattern)
    for pattern in (
        r"^#\s*noqa\b",
        r"^#\s*type:\s*ignore",
        r"^#\s*pyright:",
        r"^#\s*mypy:",
        r"^#\s*shellcheck\b",
        r"^#\s*fmt:\s*(off|on|skip)\b",
        r"^#\s*pragma:",
        r"^#\s*isort:",
        r"^#\s*ruff:",
        r"^#\s*(nosec|nosemgrep)\b",
        r"^#.*-\*-\s*coding[:=]",
        r"^#\s*yaml-language-server:",
        r"^//\s*eslint-",
        r"^/\*\s*eslint",
        r"^\{?/\*\s*eslint",
        r"^//\s*@ts-",
        r"^(//|/\*|\{/\*)\s*prettier-ignore",
        r"^//\s*biome-ignore",
        r"^/\*\s*istanbul\b",
        r"^///\s*<reference",
        r"^/\*\s*@vite-ignore",
        r"^(#|//)\s*#?\s*(end)?region\b",
        r"^#\s*hadolint\b",
        r"^/\*\s*stylelint-(disable|enable)",
        r"^/\*#\s*source(Mapping)?URL=",
    )
]
LICENSE = re.compile(r"SPDX-License-Identifier|Copyright \(c\)|Copyright \d|Licensed under|@license\b")
HEADER_LINES = 30
DOCKERFILE_DIRECTIVE = re.compile(r"#\s*(syntax|escape|check)\s*=\s*\S", re.IGNORECASE)
CSS_UNQUOTED_URL = re.compile(r"url\(\s*(?=[^\s'\"])", re.IGNORECASE)
ZERO = "0" * 40
GRANDFATHERED_BASE = "23e8ad749031e8c639fa469f272ab7ea15195645"
FULL_SHA = re.compile(r"[0-9a-f]{40}")


def dockerfile(name: str) -> bool:
    return name == "Dockerfile" or name.startswith("Dockerfile.") or name.endswith((".Dockerfile", ".dockerfile"))


def syntax(path: str) -> str | None:
    name = path.rsplit("/", 1)[-1]
    if name.endswith(".py"):
        return "python"
    if name.endswith(SCRIPT_EXTENSIONS) or JSONC_FILES.search(name):
        return "script"
    if name.endswith(".html"):
        return "html"
    if name.endswith(".css"):
        return "css"
    if name.endswith(".ini"):
        return "ini"
    if name.endswith(IGNORE_FILES):
        return "ignore"
    if name.endswith(HASH_EXTENSIONS) or name in MAKEFILES or dockerfile(name):
        return "hash"
    return None


def scanned(path: str) -> bool:
    return not path.startswith(SKIPPED_PREFIXES) and path not in GENERATED_FILES and syntax(path) is not None


class Git:
    def __init__(self, repo: str):
        self.repo = repo
        self.batch = None

    def run(self, *args: str, check: bool = True) -> subprocess.CompletedProcess:
        return subprocess.run(["git", "-C", self.repo, *args], capture_output=True, check=check)

    def text(self, rev: str, path: str) -> str | None:
        return self._object(f"{rev}:{path}")

    def blob(self, sha: str) -> str | None:
        return self._object(sha)

    def _object(self, spec: str) -> str | None:
        if self.batch is None:
            self.batch = subprocess.Popen(
                ["git", "-C", self.repo, "cat-file", "--batch"], stdin=subprocess.PIPE, stdout=subprocess.PIPE
            )
        self.batch.stdin.write(f"{spec}\n".encode())
        self.batch.stdin.flush()
        header = self.batch.stdout.readline().split()
        if not header or header[-1] in (b"missing", b"ambiguous") or len(header) != 3:
            return None
        data = self.batch.stdout.read(int(header[2]))
        self.batch.stdout.read(1)
        if header[1] != b"blob":
            return None
        return data.decode("utf-8", errors="replace")

    def exists(self, rev: str) -> bool:
        return self.commit(rev) is not None

    def commit(self, rev: str) -> str | None:
        found = self.run("rev-parse", "--verify", "--quiet", f"{rev}^{{commit}}", check=False)
        return found.stdout.decode().strip() if found.returncode == 0 else None

    def is_ancestor(self, ancestor: str, descendant: str) -> bool:
        return self.run("merge-base", "--is-ancestor", ancestor, descendant, check=False).returncode == 0

    def merge_base(self, left: str, right: str) -> str:
        found = self.run("merge-base", left, right, check=False)
        if found.returncode != 0:
            raise SystemExit(
                f"comment guard: {left[:12]} and {right[:12]} share no history, so no trusted base exists; refusing to pass"
            )
        return found.stdout.decode().strip()

    def files(self, rev: str) -> list[str]:
        listing = self.run("ls-tree", "-r", "-z", "--name-only", rev).stdout.split(b"\0")
        return [name.decode() for name in listing if name and syntax(name.decode()) is not None]


class ScriptComments:
    def __init__(self, typescript: str | None):
        self.typescript = typescript
        self.process = None

    def lines(self, path: str, text: str) -> list[tuple[int, str]]:
        if self.typescript is None:
            raise SystemExit("comment guard: a TypeScript parser is needed for scripts; pass --typescript")
        if self.process is None:
            helper = Path(__file__).with_name("comment_guard_ts.js")
            self.process = subprocess.Popen(
                ["node", str(helper), self.typescript], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True
            )
        self.process.stdin.write(json.dumps({"path": path, "text": text}) + "\n")
        self.process.stdin.flush()
        answer = json.loads(self.process.stdout.readline())
        if answer["failure"]:
            raise SystemExit(f"comment guard: could not parse {path}: {answer['failure']}")
        return [(int(number), part) for number, part in answer["lines"]]


def line_comments(text: str, prefixes: tuple[str, ...] = ("#",)) -> list[tuple[int, str]]:
    return [
        (number, line.strip()) for number, line in enumerate(text.splitlines(), 1) if line.strip().startswith(prefixes)
    ]


def python_comments(text: str) -> list[tuple[int, str]]:
    try:
        return [
            (token.start[0], token.string)
            for token in tokenize.generate_tokens(io.StringIO(text).readline)
            if token.type == tokenize.COMMENT
        ]
    except tokenize.TokenError:
        return line_comments(text)
    except SyntaxError:
        return line_comments(text)


def hash_comments(text: str) -> list[tuple[int, str]]:
    found = []
    for number, line in enumerate(text.splitlines(), 1):
        quote = None
        for index, char in enumerate(line):
            if quote:
                if char == quote:
                    quote = None
            elif char in "'\"":
                quote = char
            elif char == "#" and (index == 0 or line[index - 1] in " \t"):
                found.append((number, line[index:]))
                break
    return found


def _spans(text: str, start: int, end: int) -> list[tuple[int, str]]:
    first = text.count("\n", 0, start) + 1
    return [(first + offset, part) for offset, part in enumerate(text[start:end].split("\n"))]


def _css_string_end(text: str, start: int) -> int:
    index = start + 1
    while index < len(text):
        if text[index] == "\\":
            index += 2
        elif text[index] in (text[start], "\n"):
            return index + 1
        else:
            index += 1
    return index


def css_comments(text: str) -> list[tuple[int, str]]:
    found = []
    index = 0
    while index < len(text):
        url = CSS_UNQUOTED_URL.match(text, index)
        if text.startswith("/*", index):
            end = text.find("*/", index + 2)
            end = len(text) if end < 0 else end + 2
            found += _spans(text, index, end)
            index = end
        elif text[index] in "'\"":
            index = _css_string_end(text, index)
        elif url:
            close = text.find(")", url.end())
            index = len(text) if close < 0 else close + 1
        else:
            index += 1
    return found


def html_comments(text: str, scripts: ScriptComments) -> list[tuple[int, str]]:
    found = []
    masked = text
    for block in re.finditer(r"<script\b[^>]*>(.*?)</script>", text, re.DOTALL | re.IGNORECASE):
        offset = text.count("\n", 0, block.start(1))
        found += [(number + offset, part) for number, part in scripts.lines("inline.js", block.group(1))]
        masked = masked[: block.start(1)] + re.sub(r"[^\n]", " ", block.group(1)) + masked[block.end(1) :]
    for block in re.finditer(r"<style\b[^>]*>(.*?)</style>", masked, re.DOTALL | re.IGNORECASE):
        for comment in re.finditer(r"/\*.*?\*/", block.group(1), re.DOTALL):
            found += _spans(masked, block.start(1) + comment.start(), block.start(1) + comment.end())
    for comment in re.finditer(r"<!--.*?-->|\{#.*?#\}", masked, re.DOTALL):
        found += _spans(masked, comment.start(), comment.end())
    return sorted(found)


def comments(path: str, text: str, scripts: ScriptComments) -> list[tuple[int, str]]:
    kind = syntax(path)
    if kind == "python":
        return python_comments(text)
    if kind == "script":
        return scripts.lines(path, text)
    if kind == "html":
        return html_comments(text, scripts)
    if kind == "css":
        return css_comments(text)
    if kind == "ini":
        return line_comments(text, ("#", ";"))
    if kind == "ignore":
        return line_comments(text)
    return hash_comments(text)


def _python_tokens(text: str) -> list[tokenize.TokenInfo]:
    try:
        return list(tokenize.generate_tokens(io.StringIO(text).readline))
    except tokenize.TokenError:
        return []
    except SyntaxError:
        return []


def _string_value(parts: list[str]) -> str | None:
    values = []
    for part in parts:
        try:
            value = ast.literal_eval(part)
        except ValueError:
            return None
        except SyntaxError:
            return None
        if not isinstance(value, str):
            return None
        values.append(value)
    return " ".join("".join(values).split())


def docstrings(path: str, text: str) -> list[tuple[int, str]]:
    if not path.endswith(".py"):
        return []
    tokens = _python_tokens(text)
    found = []
    statement_start = True
    index = 0
    while index < len(tokens):
        token = tokens[index]
        if token.type in (tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT):
            statement_start = True
        elif token.type in (tokenize.NL, tokenize.COMMENT, tokenize.ENCODING):
            pass
        elif statement_start and token.type == tokenize.STRING:
            parts = []
            cursor = index
            while cursor < len(tokens) and tokens[cursor].type == tokenize.STRING:
                parts.append(tokens[cursor].string)
                cursor += 1
            while cursor < len(tokens) and tokens[cursor].type == tokenize.COMMENT:
                cursor += 1
            if cursor >= len(tokens) or tokens[cursor].type in (tokenize.NEWLINE, tokenize.ENDMARKER):
                value = _string_value(parts)
                if value is not None:
                    found.append((token.start[0], value))
            statement_start = False
            index = cursor
            continue
        else:
            statement_start = False
        index += 1
    return found


def functional(norm: str, number: int) -> bool:
    if number == 1 and norm.startswith("#!"):
        return True
    if number <= HEADER_LINES and LICENSE.search(norm):
        return True
    return any(pattern.search(norm) for pattern in PRAGMAS)


def license_headers(found: list[tuple[int, str]]) -> set[int]:
    blocks = []
    for number in sorted({number for number, _ in found}):
        if blocks and number == blocks[-1][-1] + 1:
            blocks[-1].append(number)
        else:
            blocks.append([number])
    marked = {number for number, raw in found if LICENSE.search(raw)}
    return {number for block in blocks if block[0] <= HEADER_LINES and marked.intersection(block) for number in block}


def dockerfile_directives(text: str) -> set[int]:
    found = set()
    for number, line in enumerate(text.removeprefix("\ufeff").splitlines(), 1):
        if not DOCKERFILE_DIRECTIVE.match(line.strip()):
            break
        found.add(number)
    return found


def items(path: str, text: str | None, scripts: ScriptComments) -> list[tuple[str, int, str]]:
    if text is None:
        return []
    found = []
    raw_comments = comments(path, text, scripts)
    exempt = license_headers(raw_comments)
    if dockerfile(path.rsplit("/", 1)[-1]):
        exempt |= dockerfile_directives(text)
    for number, raw in raw_comments:
        norm = raw.strip()
        functional_line = number in exempt or functional(norm, number)
        if norm and norm not in FRAGMENTS and norm not in ALEMBIC_LINES and not functional_line:
            found.append(("comment", number, norm))
    for number, norm in docstrings(path, text):
        if path.startswith(MIGRATIONS) and "Revision ID:" in norm:
            continue
        found.append(("docstring", number, norm))
    return found


class Guard:
    def __init__(self, git: Git, upstreams: list[str], scripts: ScriptComments):
        self.git = git
        self.upstreams = upstreams
        self.scripts = scripts
        self.everywhere = None
        self.history = {}

    def upstream_texts(self, path: str) -> set[tuple[str, str]]:
        texts = set()
        for rev in self.upstreams:
            texts |= {(kind, norm) for kind, _, norm in items(path, self.git.text(rev, path), self.scripts)}
        return texts

    def in_upstream_history(self, path: str, kind: str, norm: str) -> bool:
        if path not in self.history:
            log = self.git.run("log", "--format=", "--raw", "--no-abbrev", "--no-renames", *self.upstreams, "--", path)
            blobs = set()
            for line in log.stdout.decode().splitlines():
                if line.startswith(":"):
                    blobs |= {sha for sha in line.split()[2:4] if sha != ZERO}
            texts = set()
            for sha in blobs:
                texts |= {(k, n) for k, _, n in items(path, self.git.blob(sha), self.scripts)}
            self.history[path] = texts
        return (kind, norm) in self.history[path]

    def in_upstream_anywhere(self, kind: str, norm: str) -> bool:
        if self.everywhere is None:
            self.everywhere = set()
            for rev in self.upstreams:
                for path in self.git.files(rev):
                    self.everywhere |= {(k, n) for k, _, n in items(path, self.git.text(rev, path), self.scripts)}
        return (kind, norm) in self.everywhere

    def added(self, base: str, head: str) -> list[tuple[str, int, str, str]]:
        found = []
        for old, new in changed(self.git, base, head):
            if not scanned(new):
                continue
            upstream = self.upstream_texts(new)
            before = Counter(
                (kind, norm)
                for kind, _, norm in items(old, self.git.text(base, old) if old else None, self.scripts)
                if (kind, norm) not in upstream
            )
            after = [
                (kind, number, norm)
                for kind, number, norm in items(new, self.git.text(head, new), self.scripts)
                if (kind, norm) not in upstream
            ]
            excess = Counter((kind, norm) for kind, _, norm in after) - before
            for kind, number, norm in reversed(after):
                if excess[(kind, norm)] > 0:
                    excess[(kind, norm)] -= 1
                    found.append((new, number, kind, norm))
        kept = [hit for hit in found if not self.in_upstream_history(hit[0], hit[2], hit[3])]
        kept = [hit for hit in kept if not self.in_upstream_anywhere(hit[2], hit[3])]
        return sorted(kept, key=lambda hit: (hit[0], hit[1]))


def changed(git: Git, base: str, head: str) -> list[tuple[str | None, str]]:
    output = git.run("diff", "--name-status", "-z", "-M", base, head).stdout.decode().split("\0")
    pairs = []
    index = 0
    while index < len(output) - 1:
        status = output[index]
        if status.startswith(("R", "C")):
            pairs.append((output[index + 1], output[index + 2]))
            index += 3
            continue
        if not status.startswith("D"):
            pairs.append((output[index + 1], output[index + 1]))
        index += 2
    return pairs


def required_commit(git: Git, rev: str, role: str) -> str:
    sha = git.commit(rev)
    if sha is None:
        raise SystemExit(f"comment guard: {role} {rev} is not a commit in this clone; refusing to pass without it")
    return sha


def resolve_base(git: Git, head: str, given: str | None, trusted: str, grandfathered: str) -> tuple[str, str]:
    if not FULL_SHA.fullmatch(grandfathered):
        raise SystemExit(
            f"comment guard: the grandfathered base {grandfathered!r} is not a full commit sha; refusing to pass"
        )
    trusted_sha = required_commit(git, trusted, "trusted branch")
    grandfathered_sha = required_commit(git, grandfathered, "grandfathered base")
    given_sha = required_commit(git, given, "base") if given and given != ZERO else None
    base = git.merge_base(head, trusted_sha)
    reason = f"merge base with {trusted}"
    if base == head:
        if not git.is_ancestor(grandfathered_sha, head):
            raise SystemExit(
                f"comment guard: {head[:12]} is already on {trusted} but does not descend from the grandfathered base "
                f"{grandfathered_sha[:12]}; refusing to pass"
            )
        base = grandfathered_sha
        reason = f"grandfathered base, as {head[:12]} is already on {trusted}"
    if given_sha is not None:
        widened = git.merge_base(given_sha, base)
        if widened != base:
            base, reason = widened, "--base, which reaches further back than the trusted base"
    return base, reason


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="comment_guard")
    parser.add_argument("--repo", default=".")
    parser.add_argument("--base")
    parser.add_argument("--head", default="HEAD")
    parser.add_argument(
        "--trusted-branch", "--fallback-base", dest="trusted_branch", default="refs/remotes/origin/main"
    )
    parser.add_argument("--upstream", action="append", required=True)
    parser.add_argument("--typescript")
    parser.add_argument("--github", action="store_true")
    args = parser.parse_args(argv)
    git = Git(args.repo)
    missing = [rev for rev in args.upstream if not git.exists(rev)]
    if missing:
        raise SystemExit(f"comment guard: upstream refs not found: {', '.join(missing)}")
    head = required_commit(git, args.head, "head")
    base, reason = resolve_base(git, head, args.base, args.trusted_branch, GRANDFATHERED_BASE)
    hits = Guard(git, args.upstream, ScriptComments(args.typescript)).added(base, head)
    print(f"comment guard: {base[:12]}..{head[:12]} ({reason}), upstream {', '.join(args.upstream)}")
    for path, number, kind, norm in hits:
        shown = norm if len(norm) <= 100 else norm[:97] + "..."
        print(f"{path}:{number}: new {kind} that upstream does not have: {shown}")
        if args.github:
            print(f"::error file={path},line={number}::New {kind}; the fork adds no explanatory comments or docstrings")
    if hits:
        print(f"comment guard: {len(hits)} new comment or docstring line(s); remove them")
        return 1
    print("comment guard: no new comments or docstrings")
    return 0


if __name__ == "__main__":
    sys.exit(main())
