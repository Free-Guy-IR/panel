def upstream_bridge_floor(upstream):
    text = head_blob(upstream, "pyproject.toml")
    if text is None:
        return None, "no pyproject.toml"
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        return None, f"pyproject.toml is not valid TOML: {exc}"
    best = None
    for dependency in data.get("project", {}).get("dependencies", []):
        try:
            requirement = Requirement(dependency)
        except InvalidRequirement:
            continue
        if canonicalize_name(requirement.name) != BRIDGE_PACKAGE:
            continue
        for spec in requirement.specifier:
            if spec.operator not in BRIDGE_FLOOR_OPERATORS:
                continue
            try:
                version = Version(spec.version)
            except InvalidVersion:
                continue
            if best is None or version > best[0]:
                best = (version, dependency)
    if best is None:
        return None, f"no {BRIDGE_PACKAGE} lower bound in [project].dependencies"
    return best


def waiver_deadline_problem(until, today, what):
    if until is None:
        return f"{what} has no until date; a waiver needs a dated re-check"
    if today > until:
        return f"{what} expired on {until.isoformat()}; re-check it"
    if (until - today).days > DECISION_MAX_DAYS:
        return f"{what} runs until {until.isoformat()}, more than {DECISION_MAX_DAYS} days ahead; pick a nearer date"
    return None


def recorded_tag_ref(name):
    if name.startswith("refs/upstream-tags/"):
        return name
    if name.startswith(("upstream/", "refs/")):
        return None
    return f"refs/upstream-tags/{name}"


def is_prerelease_tag(name):
    text = re.sub(r"^v\.?", "", name.rsplit("/", 1)[-1], flags=re.IGNORECASE)
    try:
        return Version(text).is_prerelease
    except InvalidVersion:
        return bool(re.search(r"(?:^|[-._])(?:rc|beta|alpha|pre|preview|dev)\d*(?:$|[-._])", text, re.IGNORECASE))


def waiver_security_problem(waiver, reason, today, what, records, item, until):
    value = waiver.get("security")
    security = WAIVER_SECURITY_VALUES.get(value) if isinstance(value, str) else None
    if security is None:
        return f'{what} needs security = "yes" or "no"'
    if security:
        decision = waiver.get("owner_decision")
        decision = decision if isinstance(decision, str) else None
        return owner_decision_problem(
            decision, today, f"{what}: a security waiver", TOML_DECISION_SYNTAX
        ) or decision_problem(what, decision, records, today, until, "runs", item)
    marker = security_marker(reason)
    if marker:
        return (
            f"{what} is classified security no, but it names {marker!r}, which marks a security fix; "
            'set security = "yes"'
        )
    return None


def bridge_waiver_verdict(head, latest, today):
    text = head_blob(head, BRIDGE_WAIVER_FILE)
    if text is None:
        return 1, f"no {BRIDGE_WAIVER_FILE} on {head}; bump the bridge or add a waiver for {latest}"
    try:
        waiver = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        return 1, f"{BRIDGE_WAIVER_FILE} is not valid TOML: {exc}"
    raw_version = waiver.get("upstream_version")
    reason = waiver.get("reason")
    if not isinstance(reason, str) or not reason.strip():
        return 1, f"{BRIDGE_WAIVER_FILE} has no reason"
    try:
        waived = Version(str(raw_version))
    except InvalidVersion:
        return 1, f"{BRIDGE_WAIVER_FILE} upstream_version {raw_version!r} is not a version"
    if waived < latest:
        return 1, f"{BRIDGE_WAIVER_FILE} is stale: it waives {waived} but upstream is now at {latest}"
    if waived != latest:
        return 1, f"{BRIDGE_WAIVER_FILE} waives {waived}, which does not match upstream {latest}"
    until = waiver.get("until")
    if until is not None and (isinstance(until, datetime) or not isinstance(until, date)):
        return 1, f"{BRIDGE_WAIVER_FILE} until {until!r} is not a YYYY-MM-DD date"
    records, _ = ledger_decision_records(head_blob(head, SYNC_LEDGER_FILE), today)
    problem = waiver_deadline_problem(until, today, f"{BRIDGE_WAIVER_FILE} for {latest}") or waiver_security_problem(
        waiver, reason, today, BRIDGE_WAIVER_FILE, records, f"{BRIDGE_PACKAGE}@{latest}", until
    )
    if problem:
        return 1, problem
    return 0, f"waived by {BRIDGE_WAIVER_FILE} for {latest} until {until.isoformat()}: {reason.strip()}"


def bridge_gate(head, upstream, latest_override, today):
    print()
    print("Bridge Version")
    raw_pinned = pinned_bridge_version(head)
    if raw_pinned is None:
        print("Bridge version gate ERROR: cannot read the pinned version")
        return 2
    pinned = Version(Version(raw_pinned).public)
    print(f"  pinned: {raw_pinned} (compared as {pinned}) from uv.lock on {head}")

    sources = []
    if latest_override is not None:
        try:
            override = Version(latest_override)
        except InvalidVersion:
            print(f"Bridge version gate ERROR: --bridge-latest {latest_override!r} is not a version")
            return 2
        sources.append((override, "--bridge-latest"))
        print(f"  released: {override} from --bridge-latest (PyPI not queried)")
    else:
        released = pypi_latest_version()
        if released is None:
            print("Bridge version gate ERROR: the latest PyPI release could not be read")
            return 2
        sources.append((released, "PyPI"))
        print(f"  released: {released} from {PYPI_URL}")
    if upstream is None:
        print("  upstream floor: not checked (no upstream head)")
    else:
        floor, detail = upstream_bridge_floor(upstream)
        if floor is None:
            print(f"  upstream floor: none found on {upstream} ({detail})")
        else:
            sources.append((floor, f"pyproject.toml on {upstream}"))
            print(f"  upstream floor: {floor} from {detail!r} in pyproject.toml on {upstream}")

    latest = max(version for version, _ in sources)
    origins = [origin for version, origin in sources if version == latest]
    print(f"  upstream latest: {latest} (from {', '.join(origins)})")

    if pinned >= latest:
        if head_blob(head, BRIDGE_WAIVER_FILE) is not None:
            print(f"  note: {BRIDGE_WAIVER_FILE} is no longer needed")
        print(f"Bridge version gate OK: pinned {pinned} is not behind upstream {latest}")
        return 0
    code, message = bridge_waiver_verdict(head, latest, today)
    if code:
        print(f"Bridge version gate FAILED: pinned {pinned} is behind upstream {latest}; {message}")
    else:
        print(f"Bridge version gate OK: pinned {pinned} is behind upstream {latest}, {message}")
    return code


def strip_trailing_commas(text):
    out = []
    in_string = False
    escaped = False
    for index, char in enumerate(text):
        if in_string:
            out.append(char)
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            continue
        if char == '"':
            in_string = True
        elif char == ",":
            rest = text[index + 1 :].lstrip()
            if rest[:1] in ("}", "]"):
                continue
        out.append(char)
    return "".join(out)


def npm_lock_entries(lock, scope):
    entries = []
    for key, value in sorted((lock.get("packages") or {}).items()):
        if not isinstance(value, list) or not value or not isinstance(value[0], str):
            continue
        match = NPM_LOCK_SPEC_RE.match(value[0])
        if not match or not match.group(1).startswith(scope + "/"):
            continue
        entries.append({"key": key, "name": match.group(1), "resolved": match.group(2)})
    return entries


def upstream_npm_floors(upstream, lock_path):
    package_path = str(PurePosixPath(lock_path).with_name("package.json"))
    text = head_blob(upstream, package_path)
    if text is None:
        return {}, f"no {package_path}"
    try:
        data = json.loads(text)
    except ValueError as exc:
        return {}, f"{package_path} is not valid JSON: {exc}"
    floors = {}
    for field in NPM_DEPENDENCY_FIELDS:
        for name, spec in (data.get(field) or {}).items():
            match = NPM_SPEC_RE.match(spec.strip()) if isinstance(spec, str) else None
            if not match:
                continue
            try:
                version = Version(match.group(1))
            except InvalidVersion:
                continue
            if name not in floors or version > floors[name][0]:
                floors[name] = (version, spec)
    return floors, package_path


def load_bun_lock(ref, lock_path):
    text = head_blob(ref, lock_path)
    if text is None:
        return None
    return json.loads(strip_trailing_commas(text))


def upstream_npm_resolved(upstream, lock_path, scope):
    try:
        lock = load_bun_lock(upstream, lock_path)
    except ValueError:
        return {}
    resolved = {}
    for entry in npm_lock_entries(lock or {}, scope):
        try:
            version = Version(entry["resolved"])
        except InvalidVersion:
            continue
        if entry["name"] not in resolved or version > resolved[entry["name"]]:
            resolved[entry["name"]] = version
    return resolved


def npm_latest_version(name):
    url = f"{NPM_REGISTRY}/{urllib.parse.quote(name, safe='@')}"
    request = urllib.request.Request(
        url, headers={"Accept": "application/vnd.npm.install-v1+json", "User-Agent": "upstream-inventory"}
    )
    try:
        with urllib.request.urlopen(request, timeout=NPM_TIMEOUT) as response:
            payload = json.load(response)
        return Version(payload["dist-tags"]["latest"])
    except (OSError, ValueError, KeyError, TypeError) as exc:
        sys.stderr.write(f"error: cannot read the latest {name} release from {url}: {exc}\n")
        return None


def load_npm_waivers(head, today):
    text = head_blob(head, NPM_WAIVER_FILE)
    if text is None:
        return {}, []
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        return {}, [f"{NPM_WAIVER_FILE} is not valid TOML: {exc}"]
    waivers = {}
    errors = []
    records, _ = ledger_decision_records(head_blob(head, SYNC_LEDGER_FILE), today)
    for index, waiver in enumerate(data.get("waiver", []), 1):
        where = f"{NPM_WAIVER_FILE} waiver {index}"
        package = waiver.get("package")
        reason = waiver.get("reason")
        if not isinstance(package, str) or not package:
            errors.append(f"{where} has no package")
            continue
        if not isinstance(reason, str) or not reason.strip():
            errors.append(f"{where} ({package}) has no reason")
            continue
        try:
            version = Version(str(waiver.get("upstream_version")))
        except InvalidVersion:
            errors.append(f"{where} ({package}) upstream_version {waiver.get('upstream_version')!r} is not a version")
            continue
        until = waiver.get("until")
        if isinstance(until, datetime):
            errors.append(f"{where} ({package}) until {until!r} is a date-time; write a YYYY-MM-DD date")
            continue
        if until is not None and not isinstance(until, date):
            try:
                until = date.fromisoformat(str(until))
            except ValueError:
                errors.append(f"{where} ({package}) until {until!r} is not a YYYY-MM-DD date")
                continue
        problem = waiver_security_problem(
            waiver, reason, today, f"{where} ({package})", records, f"{package}@{waiver.get('upstream_version')}", until
        )
        if problem:
            errors.append(problem)
            continue
        waivers.setdefault(package, []).append((version, reason.strip(), until))
    return waivers, errors


def npm_waiver_verdict(waivers, name, latest, today):
    listed = waivers.get(name, [])
    for version, reason, until in listed:
        if version != latest:
            continue
        problem = waiver_deadline_problem(until, today, f"the waiver in {NPM_WAIVER_FILE} for {latest}")
        if problem:
            return 1, problem
        return 0, f"waived by {NPM_WAIVER_FILE} for {latest}: {reason}"
    if not listed:
        return 1, f"no waiver in {NPM_WAIVER_FILE}"
    newest = max(version for version, _, _ in listed)
    if newest < latest:
        return 1, f"the waiver in {NPM_WAIVER_FILE} is stale: it waives {newest} but upstream is now at {latest}"
    return 1, f"the waiver in {NPM_WAIVER_FILE} waives {newest}, which does not match upstream {latest}"


def parse_npm_overrides(values):
    overrides = {}
    for value in values:
        name, sep, version = value.rpartition("=")
        if not sep or not name:
            sys.stderr.write(f"error: --npm-latest {value!r} is not NAME=VERSION\n")
            raise SystemExit(2)
        try:
            overrides[name] = Version(version)
        except InvalidVersion:
            sys.stderr.write(f"error: --npm-latest {value!r} has an invalid version\n")
            raise SystemExit(2)
    return overrides


def npm_gate(head, upstream, lock_path, scope, overrides, today):
    print()
    print("Npm Packages")
    text = head_blob(head, lock_path)
    if text is None:
        print(f"Npm package gate ERROR: {lock_path} not found on {head}")
        return 2
    try:
        lock = json.loads(strip_trailing_commas(text))
    except ValueError as exc:
        print(f"Npm package gate ERROR: {lock_path} on {head} is not a readable bun.lock: {exc}")
        return 2
    entries = npm_lock_entries(lock, scope)
    if not entries:
        print(f"Npm package gate ERROR: no {scope} packages in {lock_path} on {head}")
        return 2
    print(f"  lock: {lock_path} on {head}, {len(entries)} {scope} entries")
    floors, floor_origin = upstream_npm_floors(upstream, lock_path) if upstream else ({}, None)
    upstream_resolved = upstream_npm_resolved(upstream, lock_path, scope) if upstream else {}
    if upstream is None:
        print("  upstream floor: not checked (no upstream head)")
    elif not floors:
        print(f"  upstream floor: none found on {upstream} ({floor_origin})")
    waivers, waiver_errors = load_npm_waivers(head, today)
    latest_seen = {}
    behind = []
    for entry in entries:
        name = entry["name"]
        floor = floors.get(name)
        try:
            pinned = Version(entry["resolved"])
        except InvalidVersion:
            required = f"; upstream requires {floor[1]}" if floor else ""
            print(f"  {entry['key']}: built from {entry['resolved']}, not version-gated here{required}")
            continue
        if name not in latest_seen:
            if name in overrides:
                latest_seen[name] = (overrides[name], "--npm-latest")
            else:
                released = npm_latest_version(name)
                if released is None:
                    print(f"Npm package gate ERROR: the latest {name} release could not be read")
                    return 2
                latest_seen[name] = (released, "npm")
        sources = [latest_seen[name]]
        if floor:
            sources.append((floor[0], f"{floor[1]!r} in {floor_origin} on {upstream}"))
        if name in upstream_resolved:
            sources.append((upstream_resolved[name], f"{lock_path} on {upstream}"))
        latest = max(version for version, _ in sources)
        origins = ", ".join(origin for version, origin in sources if version == latest)
        if pinned >= latest:
            print(f"  {entry['key']}: {pinned} is current (upstream latest {latest} from {origins})")
            continue
        code, message = npm_waiver_verdict(waivers, name, latest, today)
        print(f"  {entry['key']}: {pinned} is behind upstream {latest} (from {origins}); {message}")
        if code:
            behind.append(entry["key"])
    for message in waiver_errors:
        print(f"  waiver error: {message}")
    if behind or waiver_errors:
        reasons = []
        if behind:
            reasons.append(f"{len(behind)} lock entries behind upstream without a matching waiver")
        if waiver_errors:
            reasons.append(f"{len(waiver_errors)} waiver error(s)")
        print(f"Npm package gate FAILED: {'; '.join(reasons)}")
        return 1
    print(f"Npm package gate OK: every {scope} registry package in {lock_path} is current or waived")
    return 0


