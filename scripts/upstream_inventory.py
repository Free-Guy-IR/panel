def git(*args, stdin=None):
    result = subprocess.run(
        ["git", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        input=stdin,
        check=False,
    )
    if result.returncode != 0:
        sys.stderr.write(f"error: git {' '.join(args)}\n{result.stderr.strip()}\n")
        raise SystemExit(2)
    return result.stdout


def resolve_ref(ref):
    return git("rev-parse", "--verify", ref).strip()


def is_mechanical_path(path):
    name = path.rsplit("/", 1)[-1]
    return (
        name in LOCKFILE_NAMES
        or bool(LOCALE_RE.search(path))
        or bool(WORKFLOW_RE.match(path))
        or bool(GENERATED_PATH_RE.search(path))
    )


def head_blob(ref, path):
    result = subprocess.run(
        ["git", "show", f"{ref}:{path}"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    return result.stdout if result.returncode == 0 else None


def looks_generated(ref, path):
    content = head_blob(ref, path)
    if content is None:
        return False
    head = "\n".join(content.splitlines()[:8])
    return bool(GENERATED_HEADER_RE.search(head))


def parse_name_status(base, head):
    out = git("diff", "--name-status", "-z", "-M", base, head)
    tokens = [t for t in out.split("\0") if t]
    entries = {}
    i = 0
    while i < len(tokens):
        status = tokens[i]
        code = status[0]
        if code == "R" or code == "C":
            entries[tokens[i + 2]] = "M"
            i += 3
        else:
            mapped = {"A": "A", "M": "M", "D": "D", "T": "M"}.get(code, "M")
            entries[tokens[i + 1]] = mapped
            i += 2
    return entries


def merge_ranges(lines):
    ranges = []
    for n in sorted(set(lines)):
        if ranges and n == ranges[-1][1] + 1:
            ranges[-1][1] = n
        else:
            ranges.append([n, n])
    return ranges


def scan_symbol(path, base_lines, lineno):
    for ext_re, sym_re in SYMBOL_RULES:
        if ext_re.search(path):
            for line in reversed(base_lines[: max(lineno - 1, 0)]):
                m = sym_re.match(line)
                if m:
                    return next(g for g in m.groups() if g)
            return None
    return None


def tree_paths(ref):
    return {p for p in git("ls-tree", "-r", "-z", "--name-only", ref).split("\0") if p}


def parse_file_diffs(base, head, *extra):
    out = git("diff", "--no-color", "--no-ext-diff", *extra, "-U3", base, head)
    files = {}
    current = None
    old_path = None
    in_hunk = False
    old_ln = new_ln = 0
    for line in out.splitlines():
        if line.startswith("diff --git "):
            current = None
            old_path = None
            in_hunk = False
            continue
        if not in_hunk and line.startswith("--- "):
            target = line[4:]
            old_path = None
            if target != "/dev/null":
                old_path = target.removeprefix("a/")
            continue
        if not in_hunk and line.startswith("+++ "):
            target = line[4:]
            if target == "/dev/null":
                path = old_path
            else:
                path = target.removeprefix("b/")
            if path is None:
                current = None
                continue
            current = {"added": [], "removed": []}
            files[path] = current
            continue
        if current is None:
            continue
        m = HUNK_RE.match(line)
        if m:
            in_hunk = True
            old_ln = int(m.group(1))
            new_ln = int(m.group(3))
            continue
        if line.startswith("-"):
            current["removed"].append(old_ln)
            old_ln += 1
        elif line.startswith("+"):
            text = line[1:].strip()
            if text:
                digest = hashlib.sha1(text.encode()).hexdigest()[:12]
                current["added"].append(digest)
            new_ln += 1
        elif line.startswith("\\"):
            continue
        else:
            old_ln += 1
            new_ln += 1
    return files


def attach_ranges_and_symbols(path, base, parsed):
    removed = parsed["removed"]
    ranges = merge_ranges(removed)
    has_rule = any(ext_re.search(path) for ext_re, _ in SYMBOL_RULES)
    if not ranges:
        return []
    if not has_rule:
        return [{"start": s, "end": e, "symbol": None} for s, e in ranges]
    content = head_blob(base, path)
    base_lines = content.splitlines() if content else []
    return [{"start": s, "end": e, "symbol": scan_symbol(path, base_lines, s)} for s, e in ranges]


def empty_diff():
    return {"added": [], "removed": []}


def classify(base, head, upstream=None):
    if upstream is not None:
        return classify_dual(base, head, upstream)
    statuses = parse_name_status(base, head)
    parsed = parse_file_diffs(base, head)
    records = []
    for path, status in sorted(statuses.items()):
        diff = parsed.get(path, empty_diff())
        if is_mechanical_path(path):
            category = "mechanical"
        elif status == "A":
            category = "fork-only"
        elif status == "M" and looks_generated(head, path):
            category = "mechanical"
        elif diff["removed"]:
            category = "override"
        else:
            category = "pure-addition"
        record = {
            "path": path,
            "status": STATUS_NAMES[status],
            "category": category,
            "added_lines": 0,
            "removed_lines": len(diff["removed"]),
        }
        if category in ("pure-addition", "override"):
            record["added_lines"] = len(diff["added"])
            record["added_hashes"] = sorted(set(diff["added"]))
        if category == "override":
            record["override_ranges"] = attach_ranges_and_symbols(path, base, diff)
        records.append(record)
    return records


def load_upstream_view(base, head, upstream):
    return {
        "ref": upstream,
        "paths": tree_paths(upstream),
        "statuses": parse_name_status(upstream, head),
        "diffs": parse_file_diffs(upstream, head),
        "changes": parse_file_diffs(base, upstream, "--no-renames"),
    }


def dual_category(path, status, diff, head, view):
    if is_mechanical_path(path):
        return "mechanical"
    if status == "A" and path not in view["paths"]:
        return "fork-only"
    if looks_generated(head, path):
        return "mechanical"
    if path not in view["statuses"]:
        return None
    removed_vs_upstream = view["diffs"].get(path, empty_diff())["removed"]
    if status == "A":
        return "override" if removed_vs_upstream else "pure-addition"
    if diff["removed"] and removed_vs_upstream:
        return "override"
    if diff["added"]:
        return "pure-addition"
    return None


def dual_override_positions(path, status, diff, base, view):
    upstream_removed = view["diffs"].get(path, empty_diff())["removed"]
    if status == "A":
        return upstream_removed, view["ref"]
    ported = set(view["changes"].get(path, empty_diff())["removed"])
    own = [n for n in diff["removed"] if n not in ported]
    if own:
        return own, base
    return upstream_removed, view["ref"]


def dual_added(status, diff, path, view):
    upstream_added = view["diffs"].get(path, empty_diff())["added"]
    if status == "A":
        return upstream_added
    return list((Counter(diff["added"]) & Counter(upstream_added)).elements())


def classify_dual(base, head, upstream):
    statuses = parse_name_status(base, head)
    parsed = parse_file_diffs(base, head)
    view = load_upstream_view(base, head, upstream)
    records = []
    for path, status in sorted(statuses.items()):
        diff = parsed.get(path, empty_diff())
        category = dual_category(path, status, diff, head, view)
        if category is None:
            continue
        record = {
            "path": path,
            "status": STATUS_NAMES[status],
            "category": category,
            "added_lines": 0,
            "removed_lines": len(diff["removed"]),
        }
        if category in ("pure-addition", "override"):
            added = dual_added(status, diff, path, view)
            record["added_lines"] = len(added)
            record["added_hashes"] = sorted(set(added))
        if category == "override":
            positions, blob_ref = dual_override_positions(path, status, diff, base, view)
            record["removed_lines"] = len(positions)
            record["override_ranges"] = attach_ranges_and_symbols(path, blob_ref, {"removed": positions})
        records.append(record)
    return records


def build_report(base, head, records, upstream=None):
    summary = {c: 0 for c in CATEGORY_ORDER}
    override_lines = 0
    added_tracked = 0
    for r in records:
        summary[r["category"]] += 1
        if r["category"] == "override":
            override_lines += r["removed_lines"]
        if r["category"] in ("pure-addition", "override"):
            added_tracked += r["added_lines"]
    report = {
        "version": 1,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "base": {"ref": base, "sha": resolve_ref(base)},
        "head": {"ref": head, "sha": resolve_ref(head)},
        "summary": {
            "total_files": len(records),
            **summary,
            "override_lines": override_lines,
            "fork_added_lines_in_tracked_files": added_tracked,
        },
        "files": [{k: v for k, v in r.items() if k != "added_hashes"} for r in records],
        "files_with_hashes": records,
    }
    if upstream is not None:
        report["upstream_head"] = {"ref": upstream, "sha": resolve_ref(upstream)}
    return report


