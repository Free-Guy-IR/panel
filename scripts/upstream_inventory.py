def python_comment_lines(content):
    lines = content.splitlines()
    found = set()
    try:
        for token in tokenize.generate_tokens(io.StringIO(content).readline):
            if token.type != tokenize.COMMENT:
                continue
            number, column = token.start
            if number <= len(lines) and not lines[number - 1][:column].strip():
                found.add(number)
    except TOKENIZE_ERRORS:
        return frozenset()
    return frozenset(found)


def c_like_comment_lines(content, templates):
    code_lines = set()
    comment_lines = set()
    stack = ["code"]
    braces = [0]
    line = 1
    i = 0
    size = len(content)
    while i < size:
        char = content[i]
        state = stack[-1]
        if char == "\n":
            if state in ('"', "'") or state == "line":
                stack.pop()
            line += 1
            i += 1
            continue
        if state == "line" or state == "block":
            comment_lines.add(line)
            if state == "block" and content.startswith("*/", i):
                stack.pop()
                i += 2
                continue
            i += 1
            continue
        if char.isspace():
            i += 1
            continue
        code_lines.add(line)
        if state in ('"', "'"):
            if char == "\\":
                i += 2
                if i <= size and content[i - 1 : i] == "\n":
                    line += 1
                continue
            if char == state:
                stack.pop()
            i += 1
            continue
        if state == "`":
            if templates and char == "\\":
                if content[i + 1 : i + 2] == "\n":
                    line += 1
                i += 2
                continue
            if char == "`":
                stack.pop()
            elif templates and content.startswith("${", i):
                stack.append("code")
                braces.append(0)
                i += 2
                continue
            i += 1
            continue
        if content.startswith("//", i):
            if not content[content.rfind("\n", 0, i) + 1 : i].strip():
                code_lines.discard(line)
            stack.append("line")
            comment_lines.add(line)
            i += 2
            continue
        if content.startswith("/*", i):
            if not content[content.rfind("\n", 0, i) + 1 : i].strip():
                code_lines.discard(line)
            stack.append("block")
            comment_lines.add(line)
            i += 2
            continue
        if char in ('"', "'", "`"):
            stack.append(char)
        elif char == "{":
            braces[-1] += 1
        elif char == "}":
            if braces[-1] == 0 and len(stack) > 1:
                stack.pop()
                braces.pop()
            else:
                braces[-1] = max(0, braces[-1] - 1)
        i += 1
    return frozenset(comment_lines - code_lines)


@functools.lru_cache(maxsize=4096)
def comment_line_numbers(path, content):
    suffix = os.path.splitext(path)[1].lower()
    if suffix == ".py":
        found = python_comment_lines(content)
    elif suffix == ".go":
        if CGO_IMPORT_RE.search(content):
            return frozenset()
        found = c_like_comment_lines(content, False)
    else:
        return frozenset()
    lines = content.splitlines()
    return frozenset(
        number
        for number in found
        if number <= len(lines) and not lines[number - 1].strip().startswith(DIRECTIVE_PREFIXES)
    )


def normalise_line(path, line):
    return line.rstrip() if path.endswith(".py") else line.strip()


def kept_line_numbers(path, content):
    comments = comment_line_numbers(path, content)
    return [
        number
        for number, line in enumerate(content.splitlines(), 1)
        if number not in comments and normalise_line(path, line)
    ]


def normalised(path, content):
    lines = content.splitlines()
    return tuple(normalise_line(path, lines[number - 1]) for number in kept_line_numbers(path, content))


def hunk_side(path, side):
    marked = [(normalise_line(path, text), changed) for text, changed in side]
    marked = [(text, changed) for text, changed in marked if text]
    changed_at = [i for i, (_, changed) in enumerate(marked) if changed]
    if not changed_at:
        return None
    first, last = changed_at[0], changed_at[-1]
    texts = [text for text, _ in marked]
    return tuple(texts[:first]), tuple(texts[first : last + 1]), tuple(texts[last + 1 :])


@functools.lru_cache(maxsize=4096)
def normalised_file(ref, path):
    content = head_blob(ref, path)
    return None if content is None else normalised(path, content)


def context_follows(lines, start, step, context):
    slack = CONTEXT_SLACK
    index = start
    for expected in context:
        while 0 <= index < len(lines) and lines[index] != expected:
            if slack == 0:
                return False
            slack -= 1
            index += step
        if not 0 <= index < len(lines):
            return False
        index += step
    return True


def block_in_place(lines, side):
    if lines is None:
        return False
    before, core, after = side
    size = len(core)
    for i in range(len(lines) - size + 1):
        if lines[i : i + size] != core:
            continue
        if context_follows(lines, i - 1, -1, tuple(reversed(before))) and context_follows(lines, i + size, 1, after):
            return True
    return False


def missing_pick_lines(upstream_sha, reference, head, paths=None):
    expected = 0
    missing = []
    for hunk in commit_hunks(upstream_sha):
        path = hunk["new"] or hunk["old"]
        if paths and path not in paths:
            continue
        post = hunk_side(path, hunk["post"])
        pre = hunk_side(path, hunk["pre"])
        upstream_now = normalised_file(reference, path)
        check_post = hunk["new"] is not None and post is not None and block_in_place(upstream_now, post)
        check_pre = pre is not None and pre != post and not block_in_place(upstream_now, pre)
        if not (check_post or check_pre):
            continue
        expected += 1
        here = normalised_file(head, path)
        if check_post and not block_in_place(here, post):
            missing.append((path, post[1][0]))
        elif check_pre and block_in_place(here, pre):
            missing.append((path, f"-{pre[1][0]}"))
    return expected, missing


