def git(*args, stdin=None):
    result = subprocess.run(
        ["git", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        input=stdin,
        check=False,
    )
    if result.returncode != 0:
        sys.stderr.write(f"error: git {' '.join(args)}\n{result.stderr.strip()}\n")
        raise SystemExit(2)
    return result.stdout


def resolve_ref(ref):
    return git("rev-parse", "--verify", ref).strip()


def is_mechanical_path(path):
    name = path.rsplit("/", 1)[-1]
    return (
        name in LOCKFILE_NAMES
        or bool(LOCALE_RE.search(path))
        or bool(WORKFLOW_RE.match(path))
        or bool(GENERATED_PATH_RE.search(path))
    )


def head_blob(ref, path):
    result = subprocess.run(
        ["git", "show", f"{ref}:{path}"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    return result.stdout if result.returncode == 0 else None


def looks_generated(ref, path):
    content = head_blob(ref, path)
    if content is None:
        return False
    head = "\n".join(content.splitlines()[:8])
    return bool(GENERATED_HEADER_RE.search(head))


def parse_name_status(base, head):
    out = git("diff", "--name-status", "-z", "-M", base, head)
    tokens = [t for t in out.split("\0") if t]
    entries = {}
    i = 0
    while i < len(tokens):
        status = tokens[i]
        code = status[0]
        if code == "R" or code == "C":
            entries[tokens[i + 2]] = "M"
            i += 3
        else:
            mapped = {"A": "A", "M": "M", "D": "D", "T": "M"}.get(code, "M")
            entries[tokens[i + 1]] = mapped
            i += 2
    return entries


def merge_ranges(lines):
    ranges = []
    for n in sorted(set(lines)):
        if ranges and n == ranges[-1][1] + 1:
            ranges[-1][1] = n
        else:
            ranges.append([n, n])
    return ranges


def scan_symbol(path, base_lines, lineno):
    for ext_re, sym_re in SYMBOL_RULES:
        if ext_re.search(path):
            for line in reversed(base_lines[: max(lineno - 1, 0)]):
                m = sym_re.match(line)
                if m:
                    return next(g for g in m.groups() if g)
            return None
    return None


def tree_paths(ref):
    return {p for p in git("ls-tree", "-r", "-z", "--name-only", ref).split("\0") if p}


def parse_file_diffs(base, head, *extra):
    out = git("diff", "--no-color", "--no-ext-diff", *extra, "-U3", base, head)
    files = {}
    current = None
    old_path = None
    in_hunk = False
    old_ln = new_ln = 0
    for line in out.splitlines():
        if line.startswith("diff --git "):
            current = None
            old_path = None
            in_hunk = False
            continue
        if not in_hunk and line.startswith("--- "):
            target = line[4:]
            old_path = None
            if target != "/dev/null":
                old_path = target.removeprefix("a/")
            continue
        if not in_hunk and line.startswith("+++ "):
            target = line[4:]
            if target == "/dev/null":
                path = old_path
            else:
                path = target.removeprefix("b/")
            if path is None:
                current = None
                continue
            current = {"added": [], "removed": []}
            files[path] = current
            continue
        if current is None:
            continue
        m = HUNK_RE.match(line)
        if m:
            in_hunk = True
            old_ln = int(m.group(1))
            new_ln = int(m.group(3))
            continue
        if line.startswith("-"):
            current["removed"].append(old_ln)
            old_ln += 1
        elif line.startswith("+"):
            text = line[1:].strip()
            if text:
                digest = hashlib.sha1(text.encode()).hexdigest()[:12]
                current["added"].append(digest)
            new_ln += 1
        elif line.startswith("\\"):
            continue
        else:
            old_ln += 1
            new_ln += 1
    return files


def attach_ranges_and_symbols(path, base, parsed):
    removed = parsed["removed"]
    ranges = merge_ranges(removed)
    has_rule = any(ext_re.search(path) for ext_re, _ in SYMBOL_RULES)
    if not ranges:
        return []
    if not has_rule:
        return [{"start": s, "end": e, "symbol": None} for s, e in ranges]
    content = head_blob(base, path)
    base_lines = content.splitlines() if content else []
    return [{"start": s, "end": e, "symbol": scan_symbol(path, base_lines, s)} for s, e in ranges]


def empty_diff():
    return {"added": [], "removed": []}


def classify(base, head, upstream=None):
    if upstream is not None:
        return classify_dual(base, head, upstream)
    statuses = parse_name_status(base, head)
    parsed = parse_file_diffs(base, head)
    records = []
    for path, status in sorted(statuses.items()):
        diff = parsed.get(path, empty_diff())
        if is_mechanical_path(path):
            category = "mechanical"
        elif status == "A":
            category = "fork-only"
        elif status == "M" and looks_generated(head, path):
            category = "mechanical"
        elif diff["removed"]:
            category = "override"
        else:
            category = "pure-addition"
        record = {
            "path": path,
            "status": STATUS_NAMES[status],
            "category": category,
            "added_lines": 0,
            "removed_lines": len(diff["removed"]),
        }
        if category in ("pure-addition", "override"):
            record["added_lines"] = len(diff["added"])
            record["added_hashes"] = sorted(set(diff["added"]))
        if category == "override":
            record["override_ranges"] = attach_ranges_and_symbols(path, base, diff)
        records.append(record)
    return records


def load_upstream_view(base, head, upstream):
    return {
        "ref": upstream,
        "paths": tree_paths(upstream),
        "statuses": parse_name_status(upstream, head),
        "diffs": parse_file_diffs(upstream, head),
        "changes": parse_file_diffs(base, upstream, "--no-renames"),
    }


def dual_category(path, status, diff, head, view):
    if is_mechanical_path(path):
        return "mechanical"
    if status == "A" and path not in view["paths"]:
        return "fork-only"
    if looks_generated(head, path):
        return "mechanical"
    if path not in view["statuses"]:
        return None
    removed_vs_upstream = view["diffs"].get(path, empty_diff())["removed"]
    if status == "A":
        return "override" if removed_vs_upstream else "pure-addition"
    if diff["removed"] and removed_vs_upstream:
        return "override"
    if diff["added"]:
        return "pure-addition"
    return None


def dual_override_positions(path, status, diff, base, view):
    upstream_removed = view["diffs"].get(path, empty_diff())["removed"]
    if status == "A":
        return upstream_removed, view["ref"]
    ported = set(view["changes"].get(path, empty_diff())["removed"])
    own = [n for n in diff["removed"] if n not in ported]
    if own:
        return own, base
    return upstream_removed, view["ref"]


def dual_added(status, diff, path, view):
    upstream_added = view["diffs"].get(path, empty_diff())["added"]
    if status == "A":
        return upstream_added
    return list((Counter(diff["added"]) & Counter(upstream_added)).elements())


def classify_dual(base, head, upstream):
    statuses = parse_name_status(base, head)
    parsed = parse_file_diffs(base, head)
    view = load_upstream_view(base, head, upstream)
    records = []
    for path, status in sorted(statuses.items()):
        diff = parsed.get(path, empty_diff())
        category = dual_category(path, status, diff, head, view)
        if category is None:
            continue
        record = {
            "path": path,
            "status": STATUS_NAMES[status],
            "category": category,
            "added_lines": 0,
            "removed_lines": len(diff["removed"]),
        }
        if category in ("pure-addition", "override"):
            added = dual_added(status, diff, path, view)
            record["added_lines"] = len(added)
            record["added_hashes"] = sorted(set(added))
        if category == "override":
            positions, blob_ref = dual_override_positions(path, status, diff, base, view)
            record["removed_lines"] = len(positions)
            record["override_ranges"] = attach_ranges_and_symbols(path, blob_ref, {"removed": positions})
        records.append(record)
    return records


def build_report(base, head, records, upstream=None):
    summary = {c: 0 for c in CATEGORY_ORDER}
    override_lines = 0
    added_tracked = 0
    for r in records:
        summary[r["category"]] += 1
        if r["category"] == "override":
            override_lines += r["removed_lines"]
        if r["category"] in ("pure-addition", "override"):
            added_tracked += r["added_lines"]
    report = {
        "version": 1,
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "base": {"ref": base, "sha": resolve_ref(base)},
        "head": {"ref": head, "sha": resolve_ref(head)},
        "summary": {
            "total_files": len(records),
            **summary,
            "override_lines": override_lines,
            "fork_added_lines_in_tracked_files": added_tracked,
        },
        "files": [{k: v for k, v in r.items() if k != "added_hashes"} for r in records],
        "files_with_hashes": records,
    }
    if upstream is not None:
        report["upstream_head"] = {"ref": upstream, "sha": resolve_ref(upstream)}
    return report


def print_summary(report, top):
    s = report["summary"]
    print("Upstream Inventory")
    print(f"  base: {report['base']['ref']} ({report['base']['sha'][:12]})")
    print(f"  head: {report['head']['ref']} ({report['head']['sha'][:12]})")
    if "upstream_head" in report:
        upstream = report["upstream_head"]
        print(f"  upstream head: {upstream['ref']} ({upstream['sha'][:12]})")
    print()
    print(f"Files diverged: {s['total_files']}")
    for c in CATEGORY_ORDER:
        print(f"  {c:<14} {s[c]}")
    print()
    print(f"Override lines (upstream lines removed/changed): {s['override_lines']}")
    print(f"Fork lines added to upstream-tracked files: {s['fork_added_lines_in_tracked_files']}")
    overrides = [f for f in report["files"] if f["category"] == "override"]
    if overrides:
        print()
        print(f"Override files ({len(overrides)}):")
        for f in sorted(overrides, key=lambda x: -x["removed_lines"])[:top]:
            symbols = sorted({r["symbol"] for r in f.get("override_ranges", []) if r["symbol"]})
            sym = f"  [{', '.join(symbols[:3])}]" if symbols else ""
            print(f"  {f['removed_lines']:>5} lines  {f['path']}{sym}")
    mechanical = [f["path"] for f in report["files"] if f["category"] == "mechanical"]
    if mechanical:
        print()
        print(f"Mechanical files ({len(mechanical)}):")
        for p in mechanical:
            print(f"  {p}")


def is_ledger_path(token):
    return bool(LEDGER_TOKEN_RE.match(token) or LEDGER_DOTFILE_RE.match(token) or token in LEDGER_EXTENSIONLESS)


def load_ledger(path):
    try:
        text = Path(path).read_text()
    except OSError as exc:
        sys.stderr.write(f"error: cannot read ledger {path}: {exc}\n")
        raise SystemExit(2)
    entries = set()
    for line in text.splitlines():
        for m in BACKTICK_RE.finditer(line):
            token = m.group(1)
            if is_ledger_path(token):
                entries.add(token)
    return entries


def ledger_check(report, ledger_path):
    ledger = load_ledger(ledger_path)
    overrides = {f["path"] for f in report["files"] if f["category"] == "override"}
    outside = sorted(overrides - ledger)
    stale = sorted(ledger - overrides)
    print()
    if outside:
        print(f"Ledger check FAILED: {len(outside)} override file(s) outside {ledger_path}:")
        for p in outside:
            print(f"  {p}")
    else:
        print(f"Ledger check OK: all {len(overrides)} override file(s) listed in {ledger_path}")
    if stale:
        print(f"Ledger note: {len(stale)} listed file(s) no longer override upstream:")
        for p in stale:
            print(f"  {p}")
    return bool(outside)


def baseline_check(report, baseline_path):
    try:
        previous = json.loads(Path(baseline_path).read_text())
    except (OSError, json.JSONDecodeError) as exc:
        sys.stderr.write(f"error: cannot read baseline {baseline_path}: {exc}\n")
        raise SystemExit(2)
    prev_files = previous.get("files_with_hashes") or previous.get("files") or []
    prev_map = {f["path"]: f for f in prev_files}
    violations = []
    for f in report["files_with_hashes"]:
        if f["category"] not in ("pure-addition", "override"):
            continue
        prev = prev_map.get(f["path"])
        if prev is None:
            violations.append({"kind": "newly-diverged-file", "path": f["path"], "new_lines": f["added_lines"]})
            continue
        new_hashes = Counter(f.get("added_hashes", [])) - Counter(prev.get("added_hashes", []))
        if new_hashes:
            violations.append({"kind": "new-fork-code", "path": f["path"], "new_lines": sum(new_hashes.values())})
        if prev.get("category") == "pure-addition" and f["category"] == "override":
            violations.append({"kind": "escalated-to-override", "path": f["path"], "new_lines": 0})
    print()
    if violations:
        print(f"Baseline check: {len(violations)} boundary violation(s) vs {baseline_path}:")
        for v in violations:
            extra = f" (+{v['new_lines']} lines)" if v["new_lines"] else ""
            print(f"  [{v['kind']}] {v['path']}{extra}")
    else:
        print(f"Baseline check OK: no new fork code in upstream-tracked files vs {baseline_path}")
    return violations


def repo_root():
    return Path(git("rev-parse", "--show-toplevel").strip())


def sync_point_from_file():
    path = repo_root() / SYNC_POINT_FILE
    if not path.is_file():
        return None
    value = next((line.strip() for line in path.read_text().splitlines() if line.strip()), "")
    if not value:
        sys.stderr.write(f"error: {path} is empty; write the upstream sha the fork is synced to\n")
        raise SystemExit(2)
    return value


def resolve_upstream_head(option):
    value = sync_point_from_file() if option is None else option
    if value is None or value.lower() == "none":
        return None
    resolve_ref(f"{value}^{{commit}}")
    return value


def short_ref(refname):
    for prefix in SHORT_REF_PREFIXES:
        if refname.startswith(prefix):
            return refname[len(prefix) :]
    return refname


def list_commit_refs():
    listing = git("for-each-ref", "--format=%(refname)%00%(symref)%00%(objecttype)%00%(*objecttype)")
    refs = []
    for line in listing.splitlines():
        name, symref, objtype, peeled = line.split("\0")
        if symref:
            continue
        if objtype == "commit" or (objtype == "tag" and peeled == "commit"):
            refs.append(name)
    return refs


def ref_exists(ref):
    result = subprocess.run(
        ["git", "rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"], capture_output=True, text=True, check=False
    )
    return result.returncode == 0


def expand_tracked(patterns, option="--track", strict=True):
    all_refs = None
    tracked = {}
    for pattern in patterns:
        if GLOB_CHARS & set(pattern):
            if all_refs is None:
                all_refs = list_commit_refs()
            matched = [r for r in all_refs if any(fnmatchcase(r, prefix + pattern) for prefix in DWIM_PREFIXES)]
            if not matched and strict:
                sys.stderr.write(f"error: {option} {pattern} matched no commit refs\n")
                raise SystemExit(2)
            for refname in matched:
                tracked.setdefault(refname, refname)
        elif strict or ref_exists(pattern):
            tracked.setdefault(pattern, pattern)
    names = {key: short_ref(key) for key in tracked}
    counts = Counter(names.values())
    return [(key, names[key] if counts[names[key]] == 1 else key) for key in sorted(tracked)]


def shares_history(base, ref):
    result = subprocess.run(["git", "merge-base", base, ref], capture_output=True, text=True, check=False)
    return result.returncode == 0 and bool(result.stdout.strip())


def upstream_commits(base, tracked, require_shared_history=True):
    containing = {}
    active = []
    skipped = []
    heads = []
    for ref, name in tracked:
        tip = resolve_ref(f"{ref}^{{commit}}")
        shas = git("rev-list", "--no-merges", tip, f"^{base}").split()
        if shas and require_shared_history and not shares_history(base, tip):
            skipped.append(name)
            continue
        heads.append((tip, name))
        if shas:
            active.append((name, tip, len(shas)))
        for sha in shas:
            containing.setdefault(sha, []).append(name)
    return containing, active, skipped, heads


def load_refs_snapshot(path):
    try:
        text = Path(path).read_text()
    except FileNotFoundError:
        return [], []
    except OSError as exc:
        sys.stderr.write(f"error: cannot read refs snapshot {path}: {exc}\n")
        raise SystemExit(2)
    pairs = []
    errors = []
    for lineno, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        if not stripped:
            continue
        match = SNAPSHOT_LINE_RE.match(stripped)
        if not match:
            errors.append(f"{path}:{lineno}: expected '<40-hex sha> <ref name>'")
            continue
        pairs.append((match.group(1), match.group(2)))
    return pairs, errors


def write_refs_snapshot(path, previous, heads):
    merged = sorted(set(previous) | set(heads), key=lambda pair: (pair[1], pair[0]))
    Path(path).write_text("".join(f"{sha} {name}\n" for sha, name in merged))
    return merged


def commit_exists(sha):
    result = subprocess.run(["git", "cat-file", "-e", f"{sha}^{{commit}}"], capture_output=True, check=False)
    return result.returncode == 0


def snapshot_commits(base, pairs, live_tips, containing, active):
    errors = []
    kept = []
    for sha, name in pairs:
        if sha in live_tips:
            continue
        if not commit_exists(sha):
            errors.append(
                f"snapshot head {sha[:12]} of {name} is not in this clone; fetch it with "
                f"git fetch upstream {sha}, or record its commits by full sha in the ledger"
            )
            continue
        label = f"{name}@{sha[:12]} (snapshot)"
        shas = git("rev-list", "--no-merges", sha, f"^{base}").split()
        if shas:
            active.append((label, sha, len(shas)))
            kept.append(label)
        for commit_sha in shas:
            containing.setdefault(commit_sha, []).append(label)
    return errors, kept


def commit_metadata(base, tips):
    if not tips:
        return []
    out = git(
        "log",
        "--no-merges",
        "--topo-order",
        "--reverse",
        "--date=short",
        "--format=%H%x00%T%x00%P%x00%ad%x00%s",
        *sorted(set(tips)),
        f"^{base}",
    )
    rows = []
    for line in out.splitlines():
        sha, tree, parents, day, subject = line.split("\0", 4)
        parent = parents.split()[0] if parents else None
        rows.append({"sha": sha, "tree": tree, "parent": parent, "date": day, "subject": subject})
    return rows


def empty_commits(rows):
    parents = sorted({row["parent"] for row in rows if row["parent"]})
    if not parents:
        return set()
    out = git("log", "--no-walk=unsorted", "--stdin", "--format=%H %T", stdin="\n".join(parents) + "\n")
    trees = dict(line.split() for line in out.splitlines())
    return {row["sha"] for row in rows if row["parent"] and trees.get(row["parent"]) == row["tree"]}


def commits_on_refs(base, refs):
    names = {}
    for ref, name in refs:
        tip = resolve_ref(f"{ref}^{{commit}}")
        for sha in git("rev-list", "--no-merges", tip, f"^{base}").split():
            names.setdefault(sha, []).append(name)
    return names


def is_ancestor(ancestor, descendant):
    result = subprocess.run(
        ["git", "merge-base", "--is-ancestor", ancestor, descendant], capture_output=True, text=True, check=False
    )
    return result.returncode == 0


def sync_point_findings(upstream, tracked, release_refs):
    errors = []
    notes = []
    sync_sha = resolve_ref(f"{upstream}^{{commit}}")
    ordered = release_refs + [pair for pair in tracked if pair not in release_refs]
    if not any(is_ancestor(sync_sha, resolve_ref(f"{ref}^{{commit}}")) for ref, _ in ordered):
        errors.append(f"sync point {upstream} is not on any tracked upstream ref")
    for ref, name in release_refs:
        if not ref.startswith("refs/remotes/"):
            continue
        tip = resolve_ref(f"{ref}^{{commit}}")
        if tip == sync_sha or not is_ancestor(sync_sha, tip):
            continue
        behind = git("rev-list", "--count", "--no-merges", tip, f"^{sync_sha}").strip()
        notes.append(
            f"sync point {sync_sha[:12]} is {behind} commit(s) behind {name} ({tip[:12]}); bump {SYNC_POINT_FILE}"
        )
    return errors, notes


REVERT_RE = re.compile(r"This reverts commit ([0-9a-f]{40})")


def trailer_shas(head):
    return set(trailer_picks(head))


def trailer_picks(head):
    picks = {}
    for chunk in git("log", "--format=%H%x00%B%x01", head).split("\x01"):
        sha, sep, body = chunk.strip("\n").partition("\x00")
        if not sep:
            continue
        for upstream_sha in set(CHERRY_PICK_RE.findall(body)) | set(UPSTREAM_TRAILER_RE.findall(body)):
            picks.setdefault(upstream_sha, []).append(sha)
    return picks


def reverted_commits(head):
    return set(REVERT_RE.findall(git("log", "--format=%B", head)))


def added_lines_by_file(sha):
    files = {}
    current = None
    for line in git("show", "--format=", "--no-color", "--no-ext-diff", "-U0", "-M", sha).splitlines():
        if line.startswith("+++ "):
            target = line[4:]
            current = None if target == "/dev/null" else target.removeprefix("b/")
            continue
        if current and line.startswith("+"):
            text = line[1:].strip()
            if text:
                files.setdefault(current, set()).add(text)
    return files


def stripped_lines(ref, path):
    content = head_blob(ref, path)
    return None if content is None else {line.strip() for line in content.splitlines()}


def missing_pick_lines(upstream_sha, reference, head):
    expected = 0
    missing = []
    for path, added in sorted(added_lines_by_file(upstream_sha).items()):
        kept_upstream = stripped_lines(reference, path)
        if kept_upstream is None:
            continue
        present = stripped_lines(head, path) or set()
        for text in sorted(added & kept_upstream):
            expected += 1
            if text not in present:
                missing.append((path, text))
    return expected, missing


def pick_reference(sha, upstream, containing_tips):
    if containing_tips:
        dated = git("log", "--no-walk=unsorted", "--format=%ct %H", *sorted(set(containing_tips))).split("\n")
        return max((line.split() for line in dated if line.strip()), key=lambda item: int(item[0]))[1]
    if upstream and is_ancestor(sha, upstream):
        return upstream
    return sha


def ineffective_picks(head, candidates, upstream, tips_for):
    picks = trailer_picks(head)
    reverted = reverted_commits(head)
    findings = {}
    for sha in sorted(candidates):
        fork_commits = picks.get(sha, [])
        live = [commit for commit in fork_commits if commit not in reverted]
        if not live:
            findings[sha] = f"every fork commit carrying its trailer is reverted ({', '.join(c[:12] for c in fork_commits)})"
            continue
        expected, missing = missing_pick_lines(sha, pick_reference(sha, upstream, tips_for(sha)), head)
        if missing:
            path, text = missing[0]
            findings[sha] = (
                f"{len(missing)} of {expected} upstream line(s) it adds are not in {head}, "
                f"for example in {path}: {text[:80]!r}"
            )
    return findings


def patch_ids(shas):
    if not shas:
        return {}
    log = git(
        "log",
        "--no-walk=unsorted",
        "--stdin",
        "-p",
        "--no-color",
        "--no-ext-diff",
        "--format=commit %H",
        stdin="\n".join(shas) + "\n",
    )
    out = git("patch-id", "--stable", stdin=log)
    ids = {}
    for line in out.splitlines():
        patch_id, sha = line.split()
        ids[sha] = patch_id
    return ids


def parse_sync_ledger(path, today=None):
    try:
        text = Path(path).read_text()
    except OSError as exc:
        sys.stderr.write(f"error: cannot read ledger {path}: {exc}\n")
        raise SystemExit(2)
    entries = []
    errors = []
    section = None
    for lineno, line in enumerate(text.splitlines(), 1):
        heading = SYNC_HEADING_RE.match(line)
        if heading:
            section = SYNC_SECTIONS.get(heading.group(1).strip().lower())
            continue
        if section is None:
            continue
        item = SYNC_ITEM_RE.match(line)
        if not item:
            continue
        where = f"{path}:{lineno}"
        entry = SYNC_ENTRY_RE.match(item.group(1).strip())
        if not entry:
            errors.append(f"{where}: entry is not in the form - `<sha>` <reason>")
            continue
        token = entry.group(1).strip().lower()
        reason = entry.group(2).strip(REASON_STRIP)
        if not SHA_TOKEN_RE.match(token):
            errors.append(f"{where}: `{entry.group(1)}` is not a commit sha of at least 9 hex characters")
            continue
        if not reason:
            errors.append(f"{where}: `{token}` has no reason")
            continue
        until = UNTIL_RE.search(reason)
        if until:
            try:
                deadline = date.fromisoformat(until.group(1))
            except ValueError:
                errors.append(f"{where}: `{token}` has an invalid until date {until.group(1)}")
                continue
            if (today or datetime.now(UTC).date()) > deadline:
                errors.append(
                    f"{where}: `{token}` was decided only until {deadline.isoformat()}; re-check it, then port it "
                    "or record a new decision"
                )
                continue
        conditional = section == "waived" and bool(CONDITIONAL_TAG_RE.match(reason))
        entries.append({"token": token, "kind": section, "reason": reason, "where": where, "conditional": conditional})
    return entries, errors


def resolve_sync_entries(entries, in_range):
    resolved = {}
    errors = []
    stale = []
    duplicates = []
    for entry in entries:
        token = entry["token"]
        if len(token) == 40:
            if token not in in_range:
                stale.append(f"{entry['where']}: `{token}` is not an upstream commit past the base on a tracked ref")
                continue
            sha = token
        else:
            matches = [s for s in in_range if s.startswith(token)]
            if len(matches) > 1:
                errors.append(f"{entry['where']}: `{token}` is ambiguous ({len(matches)} upstream commits match)")
                continue
            if not matches:
                errors.append(f"{entry['where']}: `{token}` matches no upstream commit past the base on a tracked ref")
                continue
            sha = matches[0]
        if sha in resolved:
            duplicates.append(f"{entry['where']}: {sha[:12]} is already listed at {resolved[sha]['where']}")
            continue
        resolved[sha] = entry
    return resolved, errors, stale, duplicates


def base_equivalents(base, tips):
    equivalent = set()
    for tip in tips:
        for line in git("cherry", base, tip).splitlines():
            marker, _, sha = line.partition(" ")
            if marker == "-":
                equivalent.add(sha.strip())
    return equivalent


def parity_gate(
    base,
    head,
    patterns,
    ledger_path,
    snapshot_path=None,
    write_snapshot=False,
    today=None,
    require_shared_history=True,
    release_patterns=(),
    upstream=None,
):
    tracked = expand_tracked(patterns)
    containing, active, skipped, heads = upstream_commits(base, tracked, require_shared_history)
    snapshot_errors = []
    unrecorded = []
    snapshot_kept = []
    if snapshot_path:
        pairs, snapshot_errors = load_refs_snapshot(snapshot_path)
        if write_snapshot and not snapshot_errors:
            pairs = write_refs_snapshot(snapshot_path, pairs, heads)
        recorded = set(pairs)
        unrecorded = [(sha, name) for sha, name in heads if (sha, name) not in recorded]
        missing, snapshot_kept = snapshot_commits(base, pairs, {sha for sha, _ in heads}, containing, active)
        snapshot_errors += missing
    if skipped and not active:
        sys.stderr.write(
            f"error: every tracked ref with commits past {base} shares no history with it; "
            "pass --unrelated-history when the fork does not share history with upstream\n"
        )
        raise SystemExit(2)
    in_range = set(containing)
    entries, ledger_errors = parse_sync_ledger(ledger_path, today)
    resolved, resolve_errors, stale, duplicates = resolve_sync_entries(entries, in_range)
    ledger_errors += resolve_errors
    release_refs = expand_tracked(release_patterns or DEFAULT_RELEASE_REFS, option="--release-ref", strict=False)
    on_release = commits_on_refs(base, release_refs)
    copy_notes = []

    conditional = {sha for sha, entry in resolved.items() if entry["conditional"]}
    if conditional and not release_refs:
        ledger_errors.append("UNMERGED-WIP and pending waivers need at least one existing --release-ref")
    for sha in sorted(conditional & set(on_release)):
        entry = resolved.pop(sha)
        ledger_errors.append(
            f"{entry['where']}: `{sha[:12]}` is waived only while unmerged, but upstream now carries it on "
            f"{', '.join(sorted(on_release[sha]))}; port it or record a new decision"
        )

    tip_by_name = {name: tip for name, tip, _ in active}
    tip_by_name.update({name: sha for sha, name in heads})
    ineffective = ineffective_picks(
        head,
        in_range & trailer_shas(head),
        upstream,
        lambda sha: [tip_by_name[name] for name in sorted(containing.get(sha, [])) if name in tip_by_name],
    )
    coverage = {}
    for sha in (in_range & trailer_shas(head)) - set(ineffective):
        coverage[sha] = "trailer"
    for sha, entry in resolved.items():
        coverage.setdefault(sha, entry["kind"])
    ids = patch_ids(sorted(in_range))
    sources = {}
    for sha in coverage:
        if sha in ids:
            sources.setdefault(ids[sha], []).append(sha)
    for sha in sorted(in_range - set(coverage)):
        origin = sources.get(ids.get(sha), [])
        if not origin:
            continue
        if sha in on_release and all(s in conditional for s in origin):
            copy_notes.append(
                f"{sha[:12]} on {', '.join(sorted(on_release[sha]))} is a copy of {origin[0][:12]}, "
                "which is waived only while unmerged, so the copy needs its own decision"
            )
            continue
        coverage[sha] = "patch-id"
    for sha in (in_range - set(coverage)) & base_equivalents(base, [tip for _, tip, _ in active]):
        coverage[sha] = "in-base"

    sync_errors, sync_notes = sync_point_findings(upstream, tracked, release_refs) if upstream else ([], [])
    ledger_errors += sync_errors

    rows = commit_metadata(base, [tip for _, tip, _ in active])
    for sha in empty_commits([row for row in rows if row["sha"] not in coverage]):
        coverage[sha] = "empty"
    uncovered = [row for row in rows if row["sha"] not in coverage]
    counts = Counter(coverage.values())

    print()
    print("Upstream Parity")
    print(f"  base: {base} ({resolve_ref(base)[:12]})")
    print(f"  head: {head} ({resolve_ref(head)[:12]})")
    print(f"  ledger: {ledger_path}")
    print(f"  tracked refs: {len(tracked)}, with commits past base: {len(active)}")
    for name, _, count in active:
        print(f"    {name}: {count}")
    for name in skipped:
        print(f"  warning: skipped {name}: it shares no history with {base}, so it is not upstream history")
    if snapshot_path:
        print(f"  refs snapshot: {snapshot_path}, heads kept only by the snapshot: {len(snapshot_kept)}")
        for label in snapshot_kept:
            print(f"    {label}")
    print()
    print(f"Upstream commits past base: {len(in_range)}")
    for kind, label in COVERAGE_LABELS.items():
        print(f"  {label:<42} {counts[kind]}")
    print(f"  {'unported':<42} {len(uncovered)}")

    if uncovered:
        groups = {}
        for row in uncovered:
            groups.setdefault(tuple(sorted(containing[row["sha"]])), []).append(row)
        print()
        print(f"Unported upstream commits ({len(uncovered)}), grouped by the tracked refs that contain them:")
        for refs, group in groups.items():
            print(f"  on {', '.join(refs)} ({len(group)}):")
            for row in group:
                print(f"    {row['sha'][:12]}  {row['date']}  {row['subject']}")

    unlisted_picks = {sha: why for sha, why in ineffective.items() if sha not in coverage}
    if ineffective:
        print()
        print(f"Cherry-picked upstream commits whose change is not all in {head} ({len(ineffective)}):")
        for sha, why in ineffective.items():
            state = "needs a Ported by design or Waived entry" if sha in unlisted_picks else "covered by its ledger entry"
            print(f"  {sha[:12]}: {why}; {state}")

    if ledger_errors:
        print()
        print(f"Ledger errors ({len(ledger_errors)}):")
        for message in ledger_errors:
            print(f"  {message}")
    if snapshot_errors or unrecorded:
        print()
        print(f"Refs snapshot errors ({len(snapshot_errors) + len(unrecorded)}):")
        for message in snapshot_errors:
            print(f"  {message}")
        for sha, name in unrecorded:
            print(f"  upstream head {name} at {sha[:12]} is not recorded in {snapshot_path}")
        if unrecorded:
            print(f"  record the reviewed heads with --write-refs-snapshot {snapshot_path}")
    notes = stale + duplicates + copy_notes + sync_notes
    if notes:
        print()
        print(f"Ledger warnings ({len(notes)}):")
        for message in notes:
            print(f"  {message}")

    print()
    if uncovered or ledger_errors or snapshot_errors or unrecorded:
        reasons = []
        if uncovered:
            reasons.append(f"{len(uncovered)} upstream commit(s) neither ported nor listed in {ledger_path}")
        if ledger_errors:
            reasons.append(f"{len(ledger_errors)} ledger error(s)")
        if snapshot_errors or unrecorded:
            reasons.append(f"{len(snapshot_errors) + len(unrecorded)} refs snapshot error(s)")
        print(f"Upstream parity gate FAILED: {'; '.join(reasons)}")
        return 1
    print(f"Upstream parity gate OK: all {len(in_range)} upstream commit(s) are ported or listed in {ledger_path}")
    return 0


def pinned_bridge_version(head):
    text = head_blob(head, "uv.lock")
    if text is None:
        sys.stderr.write(f"error: uv.lock not found on {head}\n")
        return None
    try:
        lock = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        sys.stderr.write(f"error: uv.lock on {head} is not valid TOML: {exc}\n")
        return None
    raw = [p.get("version") for p in lock.get("package", []) if p.get("name") == BRIDGE_PACKAGE]
    try:
        versions = sorted((Version(v), v) for v in raw if v)
    except InvalidVersion as exc:
        sys.stderr.write(f"error: uv.lock on {head} has an invalid {BRIDGE_PACKAGE} version: {exc}\n")
        return None
    if not versions:
        sys.stderr.write(f"error: uv.lock on {head} has no [[package]] named {BRIDGE_PACKAGE}\n")
        return None
    return versions[0][1]


def pypi_latest_version():
    request = urllib.request.Request(
        PYPI_URL, headers={"Accept": "application/json", "User-Agent": "upstream-inventory"}
    )
    try:
        with urllib.request.urlopen(request, timeout=PYPI_TIMEOUT) as response:
            payload = json.load(response)
        return Version(payload["info"]["version"])
    except (OSError, ValueError, KeyError, TypeError) as exc:
        sys.stderr.write(f"error: cannot read the latest {BRIDGE_PACKAGE} release from {PYPI_URL}: {exc}\n")
        return None


def upstream_bridge_floor(upstream):
    text = head_blob(upstream, "pyproject.toml")
    if text is None:
        return None, "no pyproject.toml"
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        return None, f"pyproject.toml is not valid TOML: {exc}"
    best = None
    for dependency in data.get("project", {}).get("dependencies", []):
        try:
            requirement = Requirement(dependency)
        except InvalidRequirement:
            continue
        if canonicalize_name(requirement.name) != BRIDGE_PACKAGE:
            continue
        for spec in requirement.specifier:
            if spec.operator not in BRIDGE_FLOOR_OPERATORS:
                continue
            try:
                version = Version(spec.version)
            except InvalidVersion:
                continue
            if best is None or version > best[0]:
                best = (version, dependency)
    if best is None:
        return None, f"no {BRIDGE_PACKAGE} lower bound in [project].dependencies"
    return best


def bridge_waiver_verdict(head, latest):
    text = head_blob(head, BRIDGE_WAIVER_FILE)
    if text is None:
        return 1, f"no {BRIDGE_WAIVER_FILE} on {head}; bump the bridge or add a waiver for {latest}"
    try:
        waiver = tomllib.loads(text)
    except tomllib.TOMLDecodeError as exc:
        return 1, f"{BRIDGE_WAIVER_FILE} is not valid TOML: {exc}"
    raw_version = waiver.get("upstream_version")
    reason = waiver.get("reason")
    if not isinstance(reason, str) or not reason.strip():
        return 1, f"{BRIDGE_WAIVER_FILE} has no reason"
    try:
        waived = Version(str(raw_version))
    except InvalidVersion:
        return 1, f"{BRIDGE_WAIVER_FILE} upstream_version {raw_version!r} is not a version"
    if waived < latest:
        return 1, f"{BRIDGE_WAIVER_FILE} is stale: it waives {waived} but upstream is now at {latest}"
    if waived != latest:
        return 1, f"{BRIDGE_WAIVER_FILE} waives {waived}, which does not match upstream {latest}"
    return 0, f"waived by {BRIDGE_WAIVER_FILE} for {latest}: {reason.strip()}"


def bridge_gate(head, upstream, latest_override):
    print()
    print("Bridge Version")
    raw_pinned = pinned_bridge_version(head)
    if raw_pinned is None:
        print("Bridge version gate ERROR: cannot read the pinned version")
        return 2
    pinned = Version(Version(raw_pinned).public)
    print(f"  pinned: {raw_pinned} (compared as {pinned}) from uv.lock on {head}")

    sources = []
    if latest_override is not None:
        try:
            override = Version(latest_override)
        except InvalidVersion:
            print(f"Bridge version gate ERROR: --bridge-latest {latest_override!r} is not a version")
            return 2
        sources.append((override, "--bridge-latest"))
        print(f"  released: {override} from --bridge-latest (PyPI not queried)")
    else:
        released = pypi_latest_version()
        if released is None:
            print("Bridge version gate ERROR: the latest PyPI release could not be read")
            return 2
        sources.append((released, "PyPI"))
        print(f"  released: {released} from {PYPI_URL}")
    if upstream is None:
        print("  upstream floor: not checked (no upstream head)")
    else:
        floor, detail = upstream_bridge_floor(upstream)
        if floor is None:
            print(f"  upstream floor: none found on {upstream} ({detail})")
        else:
            sources.append((floor, f"pyproject.toml on {upstream}"))
            print(f"  upstream floor: {floor} from {detail!r} in pyproject.toml on {upstream}")

    latest = max(version for version, _ in sources)
    origins = [origin for version, origin in sources if version == latest]
    print(f"  upstream latest: {latest} (from {', '.join(origins)})")

    if pinned >= latest:
        if head_blob(head, BRIDGE_WAIVER_FILE) is not None:
            print(f"  note: {BRIDGE_WAIVER_FILE} is no longer needed")
        print(f"Bridge version gate OK: pinned {pinned} is not behind upstream {latest}")
        return 0
    code, message = bridge_waiver_verdict(head, latest)
    if code:
        print(f"Bridge version gate FAILED: pinned {pinned} is behind upstream {latest}; {message}")
    else:
        print(f"Bridge version gate OK: pinned {pinned} is behind upstream {latest}, {message}")
    return code


def strip_trailing_commas(text):
    out = []
    in_string = False
    escaped = False
    for index, char in enumerate(text):
        if in_string:
            out.append(char)
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            continue
        if char == '"':
            in_string = True
        elif char == ",":
            rest = text[index + 1 :].lstrip()
            if rest[:1] in ("}", "]"):
                continue
        out.append(char)
    return "".join(out)


def npm_lock_entries(lock, scope):
    entries = []
    for key, value in sorted((lock.get("packages") or {}).items()):
        if not isinstance(value, list) or not value or not isinstance(value[0], str):
            continue
        match = NPM_LOCK_SPEC_RE.match(value[0])
        if not match or not match.group(1).startswith(scope + "/"):
            continue
        entries.append({"key": key, "name": match.group(1), "resolved": match.group(2)})
    return entries


def upstream_npm_floors(upstream, lock_path):
    package_path = str(PurePosixPath(lock_path).with_name("package.json"))
    text = head_blob(upstream, package_path)
    if text is None:
        return {}, f"no {package_path}"
    try:
        data = json.loads(text)
    except ValueError as exc:
        return {}, f"{package_path} is not valid JSON: {exc}"
    floors = {}
    for field in NPM_DEPENDENCY_FIELDS:
        for name, spec in (data.get(field) or {}).items():
            match = NPM_SPEC_RE.match(spec.strip()) if isinstance(spec, str) else None
            if not match:
                continue
            try:
                version = Version(match.group(1))
            except InvalidVersion:
                continue
            if name not in floors or version > floors[name][0]:
                floors[name] = (version, spec)
    return floors, package_path


def load_bun_lock(ref, lock_path):
    text = head_blob(ref, lock_path)
    if text is None:
        return None
    return json.loads(strip_trailing_commas(text))


def upstream_npm_resolved(upstream, lock_path, scope):
    try:
        lock = load_bun_lock(upstream, lock_path)
    except ValueError:
        return {}
    resolved = {}
    for entry in npm_lock_entries(lock or {}, scope):
        try:
            version = Version(entry["resolved"])
        except InvalidVersion:
            continue
        if entry["name"] not in resolved or version > resolved[entry["name"]]:
            resolved[entry["name"]] = version
    return resolved


def npm_latest_version(name):
    url = f"{NPM_REGISTRY}/{urllib.parse.quote(name, safe='@')}"
