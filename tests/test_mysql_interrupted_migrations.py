import os

import pytest
from alembic.command import check, current, upgrade
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

from app.fork.db_rollback import current_heads, main, rollback
from tests.test_upstream_v551_migration_splice import (
    FORK_HEAD,
    HEAD,
    PROD_REVISION,
    _config,
    _quiet,
    _scratch_database,
    _sync,
    _versions,
)

SORT_ORDER_PARENT = "86f7c2a14d3e"
SORT_ORDER_REVISION = "d73f8a2c4e91"
SORT_ORDER_TABLES = ("nodes", "core_configs")
ASSOCIATION_TABLES = ("inbounds_groups_association", "users_groups_association")
REVERSE_GROUP_INDEXES = (
    ("inbounds_groups_association", "ix_inbounds_groups_association_group_id_inbound_id", "group_id, inbound_id"),
    ("users_groups_association", "ix_users_groups_association_groups_id_user_id", "groups_id, user_id"),
)
REVERSE_GROUP_COLUMNS = {"inbounds_groups_association": "group_id", "users_groups_association": "groups_id"}

pytestmark = pytest.mark.skipif(
    make_url(os.environ.get("SPLICE_SCRATCH_URL", "sqlite://")).get_backend_name() not in ("mysql", "mariadb"),
    reason="only MySQL and MariaDB commit DDL outside the migration transaction",
)


def _execute(url: str, *statements: str) -> None:
    engine = create_engine(_sync(url))
    try:
        with engine.begin() as connection:
            for statement in statements:
                connection.execute(text(statement))
    finally:
        engine.dispose()


def _sort_order_columns(url: str) -> dict[str, bool]:
    engine = create_engine(_sync(url))
    try:
        inspector = inspect(engine)
        return {
            table: "sort_order" in {column["name"] for column in inspector.get_columns(table)}
            for table in SORT_ORDER_TABLES
        }
    finally:
        engine.dispose()


def _association_indexes(url: str) -> dict[str, list]:
    engine = create_engine(_sync(url))
    try:
        inspector = inspect(engine)
        return {
            table: sorted((index["name"], tuple(index["column_names"])) for index in inspector.get_indexes(table))
            for table in ASSOCIATION_TABLES
        }
    finally:
        engine.dispose()


def _rollback(config, target: str) -> None:
    _quiet(rollback, config, target, echo=lambda _line: None)


def _core_sort_orders(url: str) -> list[tuple]:
    engine = create_engine(_sync(url))
    try:
        with engine.connect() as connection:
            return [
                tuple(row) for row in connection.execute(text("SELECT id, sort_order FROM core_configs ORDER BY id"))
            ]
    finally:
        engine.dispose()


def _foreign_key_names(url: str) -> dict[str, str]:
    engine = create_engine(_sync(url))
    try:
        inspector = inspect(engine)
        return {
            table: next(
                key["name"] for key in inspector.get_foreign_keys(table) if key["constrained_columns"] == [column]
            )
            for table, column in REVERSE_GROUP_COLUMNS.items()
        }
    finally:
        engine.dispose()


def _build_reverse_group_indexes(url: str, finished: int) -> None:
    _execute(
        url,
        *(f"CREATE INDEX {name} ON {table} ({columns})" for table, name, columns in REVERSE_GROUP_INDEXES[:finished]),
    )


@pytest.fixture(scope="module")
def fresh_head_indexes(tmp_path_factory):
    with _scratch_database(tmp_path_factory.mktemp("fresh"), "fresh_head") as url:
        _quiet(upgrade, _config(url), "head")
        return _association_indexes(url)


def test_an_upgrade_interrupted_inside_the_sort_order_revision_completes_on_the_next_run(tmp_path):
    with _scratch_database(tmp_path, "sort_order_up") as url:
        config = _config(url)
        _quiet(upgrade, config, FORK_HEAD)
        _quiet(upgrade, config, SORT_ORDER_PARENT)
        _execute(url, "ALTER TABLE nodes ADD COLUMN sort_order INTEGER NULL", "UPDATE nodes SET sort_order = id")

        _quiet(upgrade, config, "head")

        assert _versions(url) == [HEAD]
        assert _sort_order_columns(url) == {"nodes": True, "core_configs": True}


def test_a_rollback_interrupted_inside_the_sort_order_revision_completes_on_the_next_run(tmp_path):
    with _scratch_database(tmp_path, "sort_order_down") as url:
        config = _config(url)
        _quiet(upgrade, config, FORK_HEAD)
        _quiet(upgrade, config, SORT_ORDER_REVISION)
        _execute(url, "ALTER TABLE core_configs DROP COLUMN sort_order")

        _rollback(config, FORK_HEAD)

        assert _versions(url) == [FORK_HEAD]
        assert _sort_order_columns(url) == {"nodes": False, "core_configs": False}


def test_a_rollback_of_a_migration_built_database_restores_the_foreign_key_indexes(tmp_path, fresh_head_indexes):
    with _scratch_database(tmp_path, "group_fk_index") as url:
        config = _config(url)
        _quiet(upgrade, config, FORK_HEAD)
        before = _association_indexes(url)
        _quiet(upgrade, config, "head")

        _rollback(config, FORK_HEAD)

        assert _versions(url) == [FORK_HEAD]
        assert _association_indexes(url) == before
        _quiet(upgrade, config, "head")
        assert _versions(url) == [HEAD]
        assert _association_indexes(url) == fresh_head_indexes


def test_read_only_commands_leave_a_stray_sort_order_column_in_place(tmp_path):
    with _scratch_database(tmp_path, "readonly_stray") as url:
        config = _config(url)
        _quiet(upgrade, config, FORK_HEAD)
        _execute(url, "ALTER TABLE nodes ADD COLUMN sort_order INTEGER NULL")

        assert current_heads(config) == (FORK_HEAD,)
        _quiet(current, config)
        assert main(["--to", PROD_REVISION, "--url", url, "--dry-run"]) == 0

        assert _sort_order_columns(url) == {"nodes": True, "core_configs": False}


def test_alembic_check_leaves_a_missing_sort_order_column_missing(tmp_path):
    with _scratch_database(tmp_path, "readonly_missing") as url:
        config = _config(url)
        _quiet(upgrade, config, "head")
        _execute(url, "ALTER TABLE core_configs DROP COLUMN sort_order")

        with pytest.raises(AutogenerateDiffsDetected):
            _quiet(check, config)

        assert _sort_order_columns(url) == {"nodes": True, "core_configs": False}


def test_an_upgrade_with_no_step_left_keeps_the_restored_sort_order(tmp_path):
    with _scratch_database(tmp_path, "sort_order_commit") as url:
        config = _config(url)
        _quiet(upgrade, config, "head")
        _execute(
            url,
            "INSERT INTO core_configs (name, config, created_at) VALUES ('second', '{}', '2026-11-03 00:00:00')",
            "UPDATE core_configs SET sort_order = id",
        )
        before = _core_sort_orders(url)
        assert len(before) == 2
        assert all(order == identity for identity, order in before)
        _execute(url, "ALTER TABLE core_configs DROP COLUMN sort_order")

        _quiet(upgrade, config, "head")

        assert _core_sort_orders(url) == before


@pytest.mark.parametrize("dry_run", [False, True], ids=["rollback", "dry-run"])
def test_a_rollback_from_a_revision_this_release_does_not_know_is_refused(tmp_path, capsys, dry_run):
    with _scratch_database(tmp_path, "unknown_head") as url:
        _quiet(upgrade, _config(url), "head")
        _execute(url, "UPDATE alembic_version SET version_num = 'ffffffffffff'")

        exit_code = main(["--to", FORK_HEAD, "--url", url] + (["--dry-run"] if dry_run else []))

        assert exit_code == 2
        assert "which this release does not know" in capsys.readouterr().err
        assert _versions(url) == ["ffffffffffff"]


@pytest.mark.parametrize("finished", [1, 2], ids=["one-index-built", "both-indexes-built"])
def test_an_upgrade_interrupted_after_mysql_built_the_reverse_group_indexes_completes(
    tmp_path, fresh_head_indexes, finished
):
    with _scratch_database(tmp_path, f"group_index_up{finished}") as url:
        config = _config(url)
        _quiet(upgrade, config, FORK_HEAD)
        _quiet(upgrade, config, SORT_ORDER_REVISION)
        _build_reverse_group_indexes(url, finished)

        _quiet(upgrade, config, "head")

        assert _versions(url) == [HEAD]
        assert _association_indexes(url) == fresh_head_indexes


def test_a_rollback_after_an_interrupted_reverse_group_index_upgrade_restores_the_fork_head_indexes(tmp_path):
    with _scratch_database(tmp_path, "group_index_down") as url:
        config = _config(url)
        _quiet(upgrade, config, FORK_HEAD)
        before = _association_indexes(url)
        _quiet(upgrade, config, SORT_ORDER_REVISION)
        _build_reverse_group_indexes(url, 2)

        _rollback(config, FORK_HEAD)

        assert _versions(url) == [FORK_HEAD]
        assert _association_indexes(url) == before


def test_an_upgrade_drops_a_foreign_key_index_an_earlier_rollback_left_beside_the_upstream_one(
    tmp_path, fresh_head_indexes
):
    with _scratch_database(tmp_path, "group_index_leftover") as url:
        config = _config(url)
        _quiet(upgrade, config, "head")
        names = _foreign_key_names(url)
        _execute(
            url,
            *(f"CREATE INDEX {names[table]} ON {table} ({column})" for table, column in REVERSE_GROUP_COLUMNS.items()),
        )
        assert _association_indexes(url) != fresh_head_indexes

        _quiet(upgrade, config, "head")

        assert _association_indexes(url) == fresh_head_indexes
